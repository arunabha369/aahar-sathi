type IngredientKey = keyof typeof ING;

interface MealInput {
  slug: string;
  name: string;
  slot: MealSlot;
  diet: Diet;
  region: Region;
  items: MealItem[];
  protein: number;
  carbs: number;
  fat: number;
  ingredients: IngredientKey[];
}

const i = (qty: number, unit: string, food: string): MealItem => ({ qty, unit, food });

/** kcal is derived from the macros, so every meal is internally consistent by construction. */
const define = (meal: MealInput): MealData => ({
  slug: meal.slug,
  name: meal.name,
  slot: meal.slot,
  diet: meal.diet,
  region: meal.region,
  items: meal.items,
  protein: meal.protein,
  carbs: meal.carbs,
  fat: meal.fat,
  kcal: Math.round(4 * meal.protein + 4 * meal.carbs + 9 * meal.fat),
  ingredients: meal.ingredients.map((key) => ({ ...ING[key] })),
});

export const INGREDIENT_REGISTRY: Record<string, MealIngredient> = Object.fromEntries(
  Object.values(ING).map((ingredient) => [ingredient.name, { ...ingredient }]),
);

